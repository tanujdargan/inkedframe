// node tools/met.mjs -- regenerates firmware/src/met.h from tools/met.json (Met Museum public-domain works).
// Each url is https://images.metmuseum.org/CRDImages/<dept>/web-large/<file>.jpg; only <dept>/<file> is kept
// (two files end in .JPG, so the extension stays).
import { readFileSync, writeFileSync } from 'node:fs';
const works = JSON.parse(readFileSync(new URL('met.json', import.meta.url)));
const clean = s => s.replace(/[|\n"\\]/g, ' ').trim();
const lines = works.map(w => {
  const m = w.url.match(/CRDImages\/([^/]+)\/web-large\/([^/]+\.jpg)$/i);
  if (!m || /[^\x20-\x7e]/.test(w.title + w.artist)) throw new Error(`unexpected entry ${w.id}`);  // the panel font is ASCII
  return `${m[1]}/${m[2]}|${clean(w.title)}|${clean(w.artist)}`;
});
writeFileSync(new URL('../firmware/src/met.h', import.meta.url),
  `// Generated by tools/met.mjs from tools/met.json. One work per line: dept/file|title|artist\n` +
  `const int MET_COUNT = ${lines.length};\nconst char MET[] PROGMEM =\n` + lines.map(l => `  "${l}\\n"`).join('\n') + ';\n');
console.log(`${lines.length} works, ${lines.join('\n').length + 1} bytes`);
