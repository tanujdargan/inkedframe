# uv run --with pillow python3 tools/fonts.py -- regenerates firmware/src/fonts.h: Inter (SIL OFL 1.1) rendered
# at the panel's real pixel sizes into Adafruit GFX fonts. Edit FONTS to tune sizes and weights.
# The panel has no greys, so each pixel is ink where the glyph covers at least half of it.
import os, urllib.request
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, '.cache', 'Inter.ttf')
URL = 'https://raw.githubusercontent.com/google/fonts/main/ofl/inter/Inter%5Bopsz,wght%5D.ttf'
TEXT = ''.join(map(chr, range(0x20, 0x7f)))
DIGITS = '0123456789'
# name, weight, optical size (14 text .. 32 display), pixel size of the em, characters.
# Digit fonts are taller than GFX's 8-bit offsets allow below a baseline, so their cursor y is the top
# of the digits instead of the baseline.
FONTS = [
    ('Small', 500, 14, 22, TEXT),
    ('SmallBold', 650, 14, 22, TEXT),
    ('Text', 600, 20, 30, TEXT),
    ('Large', 600, 28, 40, TEXT),
    ('Num100', 600, 32, 138, DIGITS),
    ('Num150', 600, 32, 206, DIGITS),
    ('Num210', 600, 32, 289, DIGITS),
]

if not os.path.exists(TTF):
    os.makedirs(os.path.dirname(TTF), exist_ok=True)
    urllib.request.urlretrieve(URL, TTF)


def glyphs(weight, opsz, size, chars):
    f = ImageFont.truetype(TTF, size)
    f.set_variation_by_axes([opsz, weight])
    top = f.getbbox('H', anchor='ls')[1] if chars == DIGITS else 0
    for ch in chars:
        pad = size
        img = Image.new('L', (size * 2 + pad * 2, size * 2 + pad * 2), 0)
        ImageDraw.Draw(img).text((pad, pad + size), ch, font=f, fill=255, anchor='ls')
        ink = img.point(lambda v: 255 if v >= 128 else 0).getbbox()
        adv = round(f.getlength(ch))
        if not ink:
            yield ch, b'', 0, 0, adv, 0, 0
            continue
        x0, y0, x1, y1 = ink
        bits = [img.getpixel((x, y)) >= 128 for y in range(y0, y1) for x in range(x0, x1)]
        data = bytes(sum(b << (7 - i) for i, b in enumerate(bits[k:k + 8])) for k in range(0, len(bits), 8))
        yield ch, data, x1 - x0, y1 - y0, adv, x0 - pad, y0 - pad - size - top


out = ['// Generated by tools/fonts.py from Inter by The Inter Project Authors (SIL Open Font License 1.1,',
       '// see fonts-OFL.txt). Do not edit; change FONTS in tools/fonts.py and run it again.', '#pragma once', '']
for name, weight, opsz, size, chars in FONTS:
    bitmap, table = b'', []
    for ch, data, w, h, adv, dx, dy in glyphs(weight, opsz, size, chars):
        assert 0 <= w < 256 and 0 <= h < 256 and 0 <= adv < 256 and -128 <= dx < 128 and -128 <= dy < 128, (name, ch, w, h, adv, dx, dy)
        table.append(f'  {{{len(bitmap)}, {w}, {h}, {adv}, {dx}, {dy}}},  // {ch!r}')
        bitmap += data
    assert len(bitmap) < 65536, (name, len(bitmap))
    hexes = [f'0x{b:02X}' for b in bitmap]
    out.append(f'const uint8_t {name}Bitmaps[] PROGMEM = {{')
    out += ['  ' + ', '.join(hexes[i:i + 20]) + ',' for i in range(0, len(hexes), 20)]
    out += ['};', f'const GFXglyph {name}Glyphs[] PROGMEM = {{'] + table + ['};']
    out.append(f'const GFXfont {name} PROGMEM = {{(uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, {ord(chars[0])}, {ord(chars[-1])}, {min(255, round(size * 1.2))}}};')
    out.append('')
    print(f'{name}: {len(chars)} glyphs, {len(bitmap)} bytes')
open(os.path.join(HERE, '..', 'firmware', 'src', 'fonts.h'), 'w').write('\n'.join(out))
